class AppLocalizations {
  AppLocalizations(this.locale);

  final Locale locale;

  bool get isUz => locale.languageCode != 'ru';

  static AppLocalizations of(BuildContext context) =>
      Localizations.of<AppLocalizations>(context, AppLocalizations)!;

  static const LocalizationsDelegate<AppLocalizations> delegate = _AppLocalizationsDelegate();

  static const List<Locale> supportedLocales = [Locale('uz'), Locale('ru')];

  String t(String key) => isUz ? (_uz[key] ?? _ru[key] ?? key) : (_ru[key] ?? _uz[key] ?? key);

  String tf(String key, Map<String, String> params) {
    var s = t(key);
    params.forEach((k, v) {
      s = s.replaceAll(k, v);
    });
    return s;
  }
}

